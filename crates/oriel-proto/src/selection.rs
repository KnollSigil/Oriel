//! Clipboard contents of any type, offered lazily.
//!
//! The owner of a selection announces it with
//! [`ControlMessage::ClipboardOffer`](crate::ControlMessage::ClipboardOffer): the MIME types
//! it can provide, its text when small (sent right away, so text pastes instantly and
//! survives the owner disconnecting) and its files (a [`crate::xfer`] offer). The receiver
//! presents all of it as its local selection and fetches any other type only when an app
//! pastes it, over a [`BidiStreamHeader::SelectionData`](crate::BidiStreamHeader) stream:
//! images, HTML, rich text and app-specific types of any size.

use std::os::fd::OwnedFd;
use std::path::PathBuf;
use std::time::Duration;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use tokio::io::{AsyncReadExt, AsyncWriteExt};

use crate::xfer::{
    file_selection_body, file_selection_mimes, read_frame, write_frame, PORTAL_FILE_TRANSFER_MIME,
};
use crate::SUPPORTED_TEXT_MIMES;

/// The FileTransfer portal's older type name, still read by some toolkits.
pub const PORTAL_FILES_MIME: &str = "application/vnd.portal.files";

/// Prefix of the marker type an Oriel client adds to its own clipboard sources to recognise
/// their echo. Never forwarded.
pub const SOURCE_MARKER_PREFIX: &str = "application/x-oriel-source-";

/// Text up to this size travels with the offer; larger text is fetched like other types.
pub const INLINE_TEXT_MAX: usize = 64 * 1024;

/// How long a selection transfer may go without data before it is abandoned.
const IDLE_TIMEOUT: Duration = Duration::from_secs(15);

const COPY_CHUNK: usize = 64 * 1024;

/// Reply that starts a [`BidiStreamHeader::SelectionData`](crate::BidiStreamHeader) stream;
/// `Ok` is followed by the raw data up to end of stream.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SelectionDataReply {
    Ok,
    /// The offer is no longer current, or the owner refused the type.
    Unavailable,
}

/// The MIME types of a selection with `mimes` that another machine can use, when it holds
/// no files (files are announced separately and their types regenerated by the receiver).
/// Leaves out X11 atom names (`TARGETS`, `UTF8_STRING`: the receiver re-adds the text
/// aliases), the FileTransfer portal types, Ark's extraction types and GTK's in-process
/// drag marker, which only mean something on the owner's machine.
pub fn proxyable_mimes(mimes: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for mime in mimes {
        let local_only = !mime.contains('/')
            || mime == PORTAL_FILE_TRANSFER_MIME
            || mime == PORTAL_FILES_MIME
            || mime.starts_with("application/x-kde-ark-dndextract")
            // GTK's marker for drags within one process.
            || mime == "application/x-gtk-local-dnd"
            || mime.starts_with(SOURCE_MARKER_PREFIX);
        if !local_only && !out.contains(mime) {
            out.push(mime.clone());
        }
    }
    out
}

/// Whether a session drag offering `mimes` should be able to leave the session: it carries
/// data other apps understand (files, text, images), not only app-internal types.
pub fn has_interchange_mime(mimes: &[String]) -> bool {
    mimes.iter().any(|m| {
        m == crate::xfer::URI_LIST_MIME
            || m.starts_with("text/")
            || m.starts_with("image/")
            || is_text_mime(m)
    })
}

/// Whether `mime` is one of the plain-text types (and aliases) served from the same text.
pub fn is_text_mime(mime: &str) -> bool {
    SUPPORTED_TEXT_MIMES.contains(&mime)
}

/// The owner's best text type among `mimes`, to fetch text that was too large to inline.
fn owner_text_mime(mimes: &[String]) -> Option<&str> {
    SUPPORTED_TEXT_MIMES
        .iter()
        .find(|t| mimes.iter().any(|m| m == *t))
        .copied()
}

/// A selection received from the other side, presented locally.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReceivedClipboard {
    /// The owner's id for this selection, for [`fetch_selection_data`].
    pub offer_id: u64,
    pub mimes: Vec<String>,
    pub text: Option<String>,
    /// Local paths of the offered files (in the transfer mount).
    pub files: Option<Vec<PathBuf>>,
}

/// How to answer a request for one type of a [`ReceivedClipboard`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Serve {
    /// Answer locally with these bytes.
    Bytes(Vec<u8>),
    /// Fetch this type from the owner.
    Fetch(String),
    /// Register these files with the FileTransfer portal and answer with its key (see
    /// [`portal_transfer_key`]), for sandboxed apps that cannot see the paths.
    PortalFiles(Vec<PathBuf>),
    Nothing,
}

impl ReceivedClipboard {
    /// The MIME types to offer locally.
    pub fn mime_types(&self) -> Vec<String> {
        let mut out = if self.files.is_some() {
            file_selection_mimes()
        } else if self.text.is_some() || owner_text_mime(&self.mimes).is_some() {
            SUPPORTED_TEXT_MIMES
                .iter()
                .map(|s| (*s).to_string())
                .collect()
        } else {
            Vec::new()
        };
        for mime in &self.mimes {
            if !out.contains(mime) {
                out.push(mime.clone());
            }
        }
        if self.files.is_some() {
            // Last, so apps that can read the paths keep using them.
            out.push(PORTAL_FILE_TRANSFER_MIME.to_string());
            out.push(PORTAL_FILES_MIME.to_string());
        }
        out
    }

    pub fn serve(&self, mime: &str) -> Serve {
        if let Some(paths) = &self.files {
            if mime == PORTAL_FILE_TRANSFER_MIME || mime == PORTAL_FILES_MIME {
                return Serve::PortalFiles(paths.clone());
            }
            if let Some(body) = file_selection_body(mime, paths) {
                return Serve::Bytes(body);
            }
        }
        if is_text_mime(mime) {
            if let Some(text) = &self.text {
                return Serve::Bytes(text.clone().into_bytes());
            }
            if let Some(owner_mime) = owner_text_mime(&self.mimes) {
                return Serve::Fetch(owner_mime.to_string());
            }
        }
        if self.mimes.iter().any(|m| m == mime) {
            return Serve::Fetch(mime.to_string());
        }
        Serve::Nothing
    }
}

/// Register `paths` with the FileTransfer portal on `bus` and return the key a sandboxed
/// app passes to `RetrieveFiles`, followed by the NUL toolkits write after it. Blocking.
pub fn portal_transfer_key(bus: &zbus::blocking::Connection, paths: &[PathBuf]) -> Result<Vec<u8>> {
    use std::collections::HashMap;
    use std::os::unix::fs::OpenOptionsExt;
    use zbus::zvariant::{Fd, Value};

    let proxy = zbus::blocking::Proxy::new(
        bus,
        "org.freedesktop.portal.Documents",
        "/org/freedesktop/portal/documents",
        "org.freedesktop.portal.FileTransfer",
    )?;
    let mut options: HashMap<&str, Value<'_>> = HashMap::new();
    options.insert("writable", Value::from(false));
    // One app retrieves the files; the transfer then ends.
    options.insert("autostop", Value::from(true));
    let key: String = proxy.call("StartTransfer", &(options,))?;
    let files = paths
        .iter()
        .map(|p| {
            std::fs::OpenOptions::new()
                .read(true)
                .custom_flags(libc::O_PATH)
                .open(p)
                .with_context(|| format!("cannot open {}", p.display()))
        })
        .collect::<Result<Vec<_>>>()?;
    let fds: Vec<Fd<'_>> = files.iter().map(Fd::from).collect();
    let no_options: HashMap<&str, Value<'_>> = HashMap::new();
    proxy.call::<_, _, ()>("AddFiles", &(key.as_str(), fds, no_options))?;
    let mut body = key.into_bytes();
    body.push(0);
    Ok(body)
}

/// Answer a [`BidiStreamHeader::SelectionData`](crate::BidiStreamHeader) stream with the
/// data read from `source` (the read end of a pipe the selection owner writes to), or
/// `Unavailable` when there is none. Finishes the stream.
pub async fn serve_selection_data(source: Option<OwnedFd>, send: &mut quinn::SendStream) {
    let res: Result<()> = async {
        let Some(source) = source else {
            write_frame(send, &SelectionDataReply::Unavailable).await?;
            return Ok(());
        };
        let mut pipe = tokio::net::unix::pipe::Receiver::from_owned_fd(source)
            .context("selection source is not a pipe")?;
        write_frame(send, &SelectionDataReply::Ok).await?;
        let mut buf = vec![0u8; COPY_CHUNK];
        loop {
            let n = tokio::time::timeout(IDLE_TIMEOUT, pipe.read(&mut buf))
                .await
                .context("selection owner stalled")??;
            if n == 0 {
                return Ok(());
            }
            send.write_all(&buf[..n]).await?;
        }
    }
    .await;
    match res {
        Ok(()) => {
            let _ = send.finish();
        }
        Err(err) => {
            tracing::debug!(error = %format!("{err:#}"), "selection data transfer ended early");
            let _ = send.reset(quinn::VarInt::from_u32(0));
        }
    }
}

/// An async writer for a selection destination: a pipe as such, any other fd (a socket, a
/// file) through blocking writes on tokio's blocking pool.
fn async_writer(fd: OwnedFd) -> Result<Box<dyn tokio::io::AsyncWrite + Unpin + Send>> {
    use std::os::fd::AsRawFd;
    // SAFETY: fstat on a valid fd into a zeroed stat buffer.
    let is_fifo = unsafe {
        let mut st: libc::stat = std::mem::zeroed();
        libc::fstat(fd.as_raw_fd(), &mut st) == 0 && (st.st_mode & libc::S_IFMT) == libc::S_IFIFO
    };
    if is_fifo {
        Ok(Box::new(tokio::net::unix::pipe::Sender::from_owned_fd(fd)?))
    } else {
        // Written with blocking writes on the blocking pool, which a non-blocking socket
        // would fail with EAGAIN.
        // SAFETY: fcntl on a valid fd.
        unsafe {
            let flags = libc::fcntl(fd.as_raw_fd(), libc::F_GETFL);
            if flags >= 0 && flags & libc::O_NONBLOCK != 0 {
                libc::fcntl(fd.as_raw_fd(), libc::F_SETFL, flags & !libc::O_NONBLOCK);
            }
        }
        Ok(Box::new(tokio::fs::File::from_std(std::fs::File::from(fd))))
    }
}

/// Fetch type `mime` of the peer's selection `offer_id` into `dest` (the write end of a
/// pipe a local app reads from, or any writable fd). Stops early when the app closes its
/// end.
pub async fn fetch_selection_data(
    conn: &quinn::Connection,
    offer_id: u64,
    mime: String,
    dest: OwnedFd,
) -> Result<()> {
    let started = std::time::Instant::now();
    let mut dest = async_writer(dest)?;
    tracing::debug!(offer_id, %mime, "fetching selection data");
    let (mut send, mut recv) = conn.open_bi().await?;
    crate::write_bidi_stream_header(
        &mut send,
        &crate::BidiStreamHeader::SelectionData { offer_id, mime },
    )
    .await?;
    let _ = send.finish();
    let reply: SelectionDataReply = tokio::time::timeout(IDLE_TIMEOUT, read_frame(&mut recv))
        .await
        .context("selection owner did not answer")??;
    if reply != SelectionDataReply::Ok {
        bail!("selection no longer available");
    }
    let mut buf = vec![0u8; COPY_CHUNK];
    let mut total = 0usize;
    loop {
        let n = tokio::time::timeout(IDLE_TIMEOUT, recv.read(&mut buf))
            .await
            .context("selection transfer stalled")??;
        let Some(n) = n else {
            // A file destination buffers writes.
            dest.flush().await?;
            tracing::debug!(
                offer_id,
                bytes = total,
                ms = started.elapsed().as_millis() as u64,
                "fetched selection data"
            );
            return Ok(());
        };
        total += n;
        if let Err(err) = dest.write_all(&buf[..n]).await {
            // The app stopped reading (closed its end): nothing more to do.
            let _ = recv.stop(quinn::VarInt::from_u32(0));
            if err.kind() == std::io::ErrorKind::BrokenPipe {
                return Ok(());
            }
            return Err(err.into());
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn strings(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| (*s).to_string()).collect()
    }

    #[test]
    fn proxyable_drops_local_only_types() {
        let mimes = strings(&[
            "TARGETS",
            "UTF8_STRING",
            "text/plain;charset=utf-8",
            "image/png",
            "text/html",
            "application/vnd.portal.filetransfer",
            "application/x-kde-ark-dndextract-path",
            "application/x-gtk-local-dnd",
            "image/png",
        ]);
        assert_eq!(
            proxyable_mimes(&mimes),
            strings(&["text/plain;charset=utf-8", "image/png", "text/html"])
        );
    }

    #[test]
    fn received_text_serves_every_alias() {
        let clip = ReceivedClipboard {
            offer_id: 1,
            mimes: strings(&["text/plain;charset=utf-8", "text/html"]),
            text: Some("hi".into()),
            files: None,
        };
        assert!(clip.mime_types().contains(&"UTF8_STRING".to_string()));
        assert!(clip.mime_types().contains(&"text/html".to_string()));
        assert_eq!(clip.serve("STRING"), Serve::Bytes(b"hi".to_vec()));
        assert_eq!(clip.serve("text/html"), Serve::Fetch("text/html".into()));
        assert_eq!(clip.serve("image/png"), Serve::Nothing);
    }

    #[test]
    fn large_text_is_fetched_as_the_owners_type() {
        let clip = ReceivedClipboard {
            offer_id: 1,
            mimes: strings(&["text/plain"]),
            text: None,
            files: None,
        };
        assert_eq!(clip.serve("UTF8_STRING"), Serve::Fetch("text/plain".into()));
    }

    #[test]
    fn files_answer_text_with_local_paths() {
        let clip = ReceivedClipboard {
            offer_id: 1,
            mimes: Vec::new(),
            text: None,
            files: Some(vec![PathBuf::from("/m/1/a")]),
        };
        assert_eq!(clip.serve("text/plain"), Serve::Bytes(b"/m/1/a".to_vec()));
        assert!(matches!(clip.serve("text/uri-list"), Serve::Bytes(_)));
    }
}
